#!/usr/bin/env node
/**
 * .env.local → .env.sns 자동 생성 (Supabase·캠페인·자동게시 플래그)
 * OpenAI / Meta 토큰은 secrets/ 파일에서 병합
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

function parseEnv(content) {
  const out = {}
  for (const line of content.split('\n')) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const eq = t.indexOf('=')
    if (eq === -1) continue
    out[t.slice(0, eq).trim()] = t.slice(eq + 1).trim().replace(/^["']|["']$/g, '')
  }
  return out
}

function readSecretFile(rel) {
  const p = path.join(ROOT, rel)
  if (!fs.existsSync(p)) return ''
  return fs.readFileSync(p, 'utf8').trim().split('\n')[0].trim()
}

function main() {
  const localPath = path.join(ROOT, '.env.local')
  if (!fs.existsSync(localPath)) {
    console.error('.env.local 없음')
    process.exit(1)
  }
  const local = parseEnv(fs.readFileSync(localPath, 'utf8'))

  const supabaseUrl = (local.SUPABASE_URL || local.NEXT_PUBLIC_SUPABASE_URL || '').replace(/\/$/, '')
  const serviceKey = local.SUPABASE_SERVICE_ROLE_KEY || ''
  const bucket = 'sns'
  const imageBase = supabaseUrl
    ? `${supabaseUrl}/storage/v1/object/public/${bucket}/`
    : ''

  const openai =
    local.OPENAI_API_KEY ||
    readSecretFile('secrets/openai.txt') ||
    readSecretFile('secrets/openai.key')
  const gemini =
    local.GEMINI_API_KEY ||
    local.GOOGLE_AI_API_KEY ||
    readSecretFile('secrets/gemini.txt') ||
    readSecretFile('secrets/google-ai.txt')

  const imageProvider =
    local.SNS_IMAGE_PROVIDER ||
    (gemini ? 'gemini' : openai ? 'openai' : 'pollinations')

  const metaToken =
    readSecretFile('secrets/meta-token.txt') || local.META_ACCESS_TOKEN || ''
  const igSua = readSecretFile('secrets/instagram-sua-id.txt') || local.INSTAGRAM_SUA_USER_ID || ''
  const igEthan = readSecretFile('secrets/instagram-ethan-id.txt') || local.INSTAGRAM_ETHAN_USER_ID || ''

  const lines = [
    '# auto-generated by scripts/setup-sns-from-local.mjs',
    `SNS_CAMPAIGN_START=${new Date().toISOString().slice(0, 10)}`,
    'SNS_AUTO_PUBLISH=true',
    'SNS_SKIP_IMAGES=false',
    'SNS_PUBLISH_DRY_RUN=false',
    `SNS_IMAGE_PROVIDER=${imageProvider}`,
    '',
    `SUPABASE_URL=${supabaseUrl}`,
    `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}`,
    `SNS_STORAGE_BUCKET=${bucket}`,
    `SNS_IMAGE_BASE_URL=${imageBase}`,
    '',
  ]

  if (gemini) lines.push(`GEMINI_API_KEY=${gemini}`)
  if (openai) lines.push(`OPENAI_API_KEY=${openai}`)
  if (metaToken) lines.push(`META_ACCESS_TOKEN=${metaToken}`)
  if (igSua) lines.push(`INSTAGRAM_SUA_USER_ID=${igSua}`)
  if (igEthan) lines.push(`INSTAGRAM_ETHAN_USER_ID=${igEthan}`)

  const outPath = path.join(ROOT, '.env.sns')
  fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8')

  // .env.local 에 OPENAI 키 동기화 (secrets 에만 있을 때)
  if (openai && !local.OPENAI_API_KEY) {
    const append = localPath.endsWith('\n') ? '' : '\n'
    if (!fs.readFileSync(localPath, 'utf8').includes('OPENAI_API_KEY=')) {
      fs.appendFileSync(
        localPath,
        `${append}\n# SNS DALL-E (from secrets/openai.txt)\nOPENAI_API_KEY=${openai}\n`,
        'utf8'
      )
      console.log('.env.local 에 OPENAI_API_KEY 추가됨')
    }
  }

  console.log('생성:', outPath)
  console.log('  SNS_AUTO_PUBLISH=true')
  console.log('  SNS_IMAGE_BASE_URL=', imageBase || '(Supabase URL 없음)')
  if (!gemini && !openai) {
    console.log('  ⚠ 이미지: secrets/gemini.txt (Nano Banana, 무료한도) 또는 pollinations(품질↓)')
  }
  if (!metaToken || !igSua || !igEthan) {
    console.log('  ⚠ Instagram: secrets/meta-token.txt, instagram-sua-id.txt, instagram-ethan-id.txt 필요')
  }
}

main()
